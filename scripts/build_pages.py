"""Generate GitHub Pages entries that share the prototype assets."""

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
PROTOTYPE = ROOT / "prototype"


def outputs():
    yield ROOT / "index.html", (PROTOTYPE / "index.html").read_text(encoding="utf-8")
    for name in ("web.html", "mobile.html"):
        source = (PROTOTYPE / name).read_text(encoding="utf-8")
        if source.count("<head>") != 1:
            raise ValueError(f"Expected one head element in {name}")
        source = source.replace(
            "<head>",
            '<head>\n  <!-- Generated by scripts/build_pages.py. -->\n  <base href="./prototype/">',
            1,
        )
        yield ROOT / name, source
    yield ROOT / ".nojekyll", ""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated entries without writing")
    args = parser.parse_args()
    stale = []
    for destination, content in outputs():
        if args.check:
            if not destination.exists() or destination.read_text(encoding="utf-8") != content:
                stale.append(destination.name)
        else:
            destination.write_text(content, encoding="utf-8", newline="\n")
            print(f"Generated {destination.name}")
    if stale:
        raise SystemExit("Run python scripts/build_pages.py: " + ", ".join(stale))
    if args.check:
        print("GitHub Pages entries are up to date.")


if __name__ == "__main__":
    main()
